-- =============================================================================
-- Supabase Postgres Sync Target Schema
-- Mirrors the local SQLite 3-layer medication schema for offline-first sync.
-- Money is strictly INTEGER minor units (cents). unit_price_cents NULL = unknown.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.medication (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- LAYER 1: catalog / reference (imported, not typed by hand)
  brand_name TEXT NOT NULL,
  generic_name TEXT,
  strength TEXT,
  dosage_form TEXT,
  category TEXT,
  atc_code TEXT,
  manufacturer TEXT,
  barcode TEXT UNIQUE,
  storage TEXT,
  -- LAYER 2: local inventory (pharmacist only)
  zone TEXT,
  shelf TEXT,
  bin TEXT,
  location_note TEXT,
  reorder_level INTEGER DEFAULT 10,
  lead_time_days INTEGER DEFAULT 7,
  -- LAYER 3: price (pharmacist confirms; never fetched silently)
  unit_price_cents INTEGER, -- NULL = unknown, NOT 0
  cost_price_cents INTEGER,
  currency TEXT DEFAULT 'USD',
  units_per_pack INTEGER DEFAULT 1,
  price_source TEXT CHECK (price_source IS NULL OR price_source IN ('manual', 'official_tariff', 'imported')),
  price_confirmed SMALLINT DEFAULT 0 CHECK (price_confirmed IN (0, 1)),
  price_updated_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.medication_alias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_id BIGINT REFERENCES public.medication(id) ON DELETE CASCADE,
  alias TEXT
);

CREATE TABLE IF NOT EXISTS public.batch (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_id BIGINT REFERENCES public.medication(id) ON DELETE CASCADE,
  lot_number TEXT,
  quantity INTEGER NOT NULL,
  expiry_date DATE,
  received_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.stock_movement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_id BIGINT REFERENCES public.medication(id),
  batch_id BIGINT REFERENCES public.batch(id),
  delta INTEGER,
  reason TEXT,
  user_id TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.price_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_id BIGINT REFERENCES public.medication(id),
  unit_price_cents INTEGER,
  source TEXT CHECK (source IS NULL OR source IN ('manual', 'official_tariff', 'imported')),
  changed_by TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes matching SQLite local schema
CREATE INDEX IF NOT EXISTS idx_pg_medication_barcode ON public.medication(barcode);
CREATE INDEX IF NOT EXISTS idx_pg_medication_brand_name ON public.medication(brand_name);
CREATE INDEX IF NOT EXISTS idx_pg_medication_alias_alias ON public.medication_alias(alias);
CREATE INDEX IF NOT EXISTS idx_pg_price_history_medication_id ON public.price_history(medication_id);

-- Append-only enforcement function for stock_movement and price_history
CREATE OR REPLACE FUNCTION public.prevent_append_only_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION '% is append-only: % is prohibited', TG_TABLE_NAME, TG_OP;
END;
$$;

DROP TRIGGER IF EXISTS trg_pg_stock_movement_append_only ON public.stock_movement;
CREATE TRIGGER trg_pg_stock_movement_append_only
BEFORE UPDATE OR DELETE ON public.stock_movement
FOR EACH ROW EXECUTE FUNCTION public.prevent_append_only_mutation();

DROP TRIGGER IF EXISTS trg_pg_price_history_append_only ON public.price_history;
CREATE TRIGGER trg_pg_price_history_append_only
BEFORE UPDATE OR DELETE ON public.price_history
FOR EACH ROW EXECUTE FUNCTION public.prevent_append_only_mutation();
