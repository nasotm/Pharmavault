function escapeCsvCell(value: string): string {
  if (value.includes(',') || value.includes('"') || value.includes('\n')) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

function serializeSeedRowsToCsv(rows: readonly SampleRowSeed[]): string {
  const headers = [
    'brand_name',
    'generic_name',
    'strength',
    'dosage_form',
    'category',
    'atc_code',
    'manufacturer',
    'barcode',
    'storage',
    'zone',
    'shelf',
    'bin',
    'location_note',
    'quantity',
    'expiry_date',
    'lot_number',
    'reorder_level',
    'lead_time_days',
    'unit_price_cents',
    'cost_price_cents',
    'currency',
    'units_per_pack',
  ];

  const lines = [headers.join(',')];
  for (const r of rows) {
    lines.push(
      [
        r.brand,
        r.generic,
        r.strength,
        r.form,
        r.category,
        r.atc,
        r.manufacturer,
        r.barcode,
        r.storage,
        r.zone,
        r.shelf,
        r.bin,
        r.note,
        r.qty,
        r.expiry,
        r.lot,
        r.reorder,
        r.leadDays,
        r.unitPrice,
        r.costPrice,
        r.currency,
        r.packSize,
      ]
        .map(escapeCsvCell)
        .join(','),
    );
  }
  return lines.join('\n');
}

